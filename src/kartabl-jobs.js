/* متنی که داخلِ صفحه گذاشته می‌شود. برای شغل‌های ناشناخته یا وقتی
   شغلی انتخاب نشده، null برمی‌گردد و قالب سراغِ پیش‌فرضِ خودش می‌رود. */
export function jobSeed(jobId) {
  const j = JOBS[jobId];
  if (!j) return 'null';
  return JSON.stringify({ label: j.label, categories: j.categories, tasks: j.tasks })
    .replace(/</g, '\\u003c');   /* تا رشته نتواند از <script> بیرون بزند */
}
