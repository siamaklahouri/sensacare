/* ==================== فایل‌های نمونهٔ اکسل ====================
   دو آزمونِ «ورودِ اکسل» به پنج فایلِ آماده بند بودند که بیرونِ مخزن،
   در یک پوشهٔ موقت نشسته بودند. آن پوشه که پاک شد، آزمون‌ها افتادند و
   چون در فهرستِ run-tests.sh هم نبودند، کسی خبردار نشد.

   حالا همان فایل‌ها سرِ هر اجرا ساخته می‌شوند — با buildXlsx خودِ
   برنامه، نه یک نویسندهٔ جداگانه. یعنی فایلِ «خروجیِ کارتابل» واقعاً
   همان چیزی است که کارتابل می‌سازد، و اگر روزی قالبِ خروجی عوض شود،
   آزمونِ ورودی هم همان‌جا با آن عوض می‌شود.

   سرستون‌ها از روی XS_* در it.tpl و fin.tpl برداشته شده‌اند. */
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { buildXlsx } from '../src/kartabl-xlsx.js';

const write = async (dir, name, sheets) => {
  const buf = await buildXlsx(sheets);
  writeFileSync(join(dir, name), Buffer.from(buf));
};

