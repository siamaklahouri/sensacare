CREATE INDEX IF NOT EXISTS admin_log_at ON admin_log(at DESC);

-- ۳۱ | سفارش‌های کارتابل (sltech.ir)
-- فروشگاهِ سِنسا جدول‌های خودش را دارد و این‌جا کاری با آن‌ها نداریم:
-- سفارشِ کارتابل یک پلن است و یک خریدار، نه سبد و کرایه و تخفیف.
-- شمارهٔ فاکتور همان کلید است، چون همان چیزی است که خریدار موقع
-- فرستادنِ فیش می‌نویسد.
CREATE TABLE IF NOT EXISTS sl_orders (
  id       TEXT PRIMARY KEY,
  created  INTEGER NOT NULL,
  plan     TEXT NOT NULL DEFAULT '',
  price    INTEGER NOT NULL DEFAULT 0,
  days     INTEGER NOT NULL DEFAULT 0,
  kind     TEXT NOT NULL DEFAULT 'gen',
  job      TEXT NOT NULL DEFAULT '',
  name     TEXT NOT NULL DEFAULT '',
  contact  TEXT NOT NULL DEFAULT '',
  seats    INTEGER NOT NULL DEFAULT 1,
  note     TEXT NOT NULL DEFAULT '',
  status   TEXT NOT NULL DEFAULT 'new',   -- new | paid | done | canceled
  slug     TEXT NOT NULL DEFAULT '',      -- کارتابلی که برایش ساخته شد
  updated  INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS sl_orders_created ON sl_orders(created DESC);

-- ۳۲ | کدهای تخفیفِ کارتابل
-- جدولِ «coupons» مالِ فروشگاهِ سِنساست و همان‌جا می‌ماند: دو کسب‌وکارِ
-- جدا، پس کدِ یکی نباید روی آن یکی کار کند.
CREATE TABLE IF NOT EXISTS sl_coupons (
  code    TEXT PRIMARY KEY,            -- همیشه با حروف بزرگ ذخیره می‌شود
  kind    TEXT NOT NULL DEFAULT 'percent',  -- percent یا amount
  value   INTEGER NOT NULL DEFAULT 0,  -- درصد، یا مبلغ به تومان
  min_total INTEGER NOT NULL DEFAULT 0,
  max_uses  INTEGER NOT NULL DEFAULT 0,     -- ۰ یعنی بی‌نهایت
  used    INTEGER NOT NULL DEFAULT 0,
  expires INTEGER NOT NULL DEFAULT 0,       -- ۰ یعنی بی‌تاریخ
  active  INTEGER NOT NULL DEFAULT 1,
  note    TEXT NOT NULL DEFAULT '',
  created INTEGER NOT NULL DEFAULT 0
);

-- سفارش باید بداند با کدام کد و چقدر تخفیف بسته شده، وگرنه فردا
-- معلوم نیست چرا مبلغش با قیمتِ پلن نمی‌خواند. این دو ستون عمداً
-- این‌جا با ALTER اضافه نمی‌شوند: «ADD COLUMN» دوبار اجرا نمی‌شود و
-- این فایل هر بار استقرار دوباره اجرا می‌گردد — یک خطایش کلِ استقرار
-- را می‌خواباند. به‌جایش sltech-shop.js موقع کار خودش می‌سازدشان.

-- ۳۳ | بخش‌های مشترک بین چند کارتابل
-- دادهٔ هر کارتابل تا حالا مالِ خودش بود. این دو جدول برای چیزهایی است
-- که چند کارتابل با هم دارند و هر کدام می‌توانند عوضش کنند.
--
-- چرا ردیف‌به‌ردیف و نه یک تکهٔ JSON مثل بقیه؟ بقیهٔ داده‌ها یک صاحب
-- دارند و «آخرین نوشته برنده» مشکلی نمی‌سازد. این‌جا دو نفر هم‌زمان
-- باز کرده‌اند؛ اگر کلِ جدول را بفرستند، آن‌که دیرتر ذخیره کرده کارِ
-- اولی را پاک می‌کند.
--
-- «dead» یعنی حذفِ نرم: اگر ردیف را واقعاً پاک کنیم، مرورگرِ آن یکی که
-- هر چند ثانیه «از فلان لحظه چه چیزی عوض شده؟» می‌پرسد هیچ‌وقت نمی‌فهمد
-- ردیف رفته است.
CREATE TABLE IF NOT EXISTS shared_boxes (
  id      TEXT PRIMARY KEY,
  title   TEXT NOT NULL DEFAULT '',
  type    TEXT NOT NULL DEFAULT 'notes',
  members TEXT NOT NULL DEFAULT '[]',   -- آرایهٔ JSON از slugِ کارتابل‌ها
  created INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS shared_rows (
  box     TEXT NOT NULL,
  rid     TEXT NOT NULL,
  v       TEXT NOT NULL DEFAULT '{}',
  updated INTEGER NOT NULL DEFAULT 0,
  by      TEXT NOT NULL DEFAULT '',     -- کدام کارتابل آخرین بار دست زد
  dead    INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (box, rid)
);

-- پرسشِ همیشگیِ صفحه «از این لحظه به بعد چه عوض شده؟» است، پس همین
-- دو ستون با هم ایندکس می‌شوند.
CREATE INDEX IF NOT EXISTS shared_rows_box_upd ON shared_rows(box, updated);
